"""Builds index.html from index.template.html.

Injects the exploded-view drawing (tools/exploded_view.py), its numbered
callouts and the services list, and writes css/exploded.css with the
per-part assembly offsets used by the opening animation.

Usage:  python tools/build.py
"""
from pathlib import Path
import html
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from exploded_view import render, part_thumb  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

# number, part id, symptom (how the visitor says it), part name, what gets done
SERVICES = [
    ("02", "ssd", "Windows no arranca, tiene virus o se llena de publicidad",
     "Disco y sistema", "Instalación de Windows, limpieza de virus y programas basura, rescate de fotos y documentos."),
    ("03", "ram", "Se tilda cuando abrís varias cosas a la vez",
     "Memoria RAM", "Prueba de las memorias, reemplazo de módulos fallados y ampliación de capacidad."),
    ("04", "cooler", "Se apaga sola, calienta o suena como un avión",
     "Procesador y cooler", "Limpieza interna, pasta térmica nueva y control de temperaturas."),
    ("05", "fuente", "No prende, o se reinicia sin aviso",
     "Fuente de alimentación", "Medición de la fuente y reemplazo por una adecuada para tu equipo."),
    ("06", "gpu", "Pantalla negra, rayas, o los juegos se traban",
     "Placa de video", "Diagnóstico de la placa, drivers, limpieza y cambio o mejora de placa."),
    ("07", "gabinete", "Querés una PC más rápida o armar una nueva",
     "Armado y mejoras", "Te ayudo a elegir piezas según tu uso y presupuesto, y armo el equipo."),
    ("08", "placa", "Anda mal y no sabés por qué",
     "Diagnóstico general", "Reviso pieza por pieza hasta encontrar la causa y te la explico."),
]


def callouts(meta, linked=True):
    vb = meta["viewBox"]
    right_x = vb[0] + vb[2] - 34
    left_x = vb[0] + 30
    slots = {  # (column, label y), ordered to keep leader lines from crossing
        "gabinete": ("L", -330), "gpu": ("L", 150),
        "placa": ("R", -300), "ram": ("R", -225), "cooler": ("R", -135),
        "fuente": ("R", 205), "ssd": ("R", 300),
    }
    out = []
    for num, pid, symptom, part, _ in SERVICES:
        ax, ay = meta["anchors"][pid]
        side_name, ly = slots[pid]
        lx = left_x if side_name == "L" else right_x
        side = -1 if lx > ax else 1
        knee_x = lx + side * 30
        label = html.escape(f"{num}: {part}. {symptom}")
        open_tag = (f'<a class="callout" href="#svc-{pid}" data-part="{pid}" aria-label="{label}">' if linked
                    else f'<g class="callout" data-part="{pid}">')
        out.append(
            open_tag +
            f'<polyline class="leader" points="{ax:.1f},{ay:.1f} {knee_x:.1f},{ly:.1f} {lx:.1f},{ly:.1f}"/>'
            f'<circle class="leader-dot" cx="{ax:.1f}" cy="{ay:.1f}" r="3.2"/>'
            f'<circle class="bubble" cx="{lx:.1f}" cy="{ly:.1f}" r="19"/>'
            f'<text x="{lx:.1f}" y="{ly:.1f}" dy="0.36em">{num}</text>' + ('</a>' if linked else '</g>')
        )
    return "\n".join(out)


def services():
    rows = []
    for num, pid, symptom, part, fix in SERVICES:
        thumb_vb, thumb_body = part_thumb(pid)
        rows.append(f'''          <li class="part-row" id="svc-{pid}" data-part="{pid}" tabindex="-1">
            <span class="part-num" aria-hidden="true">{num}</span>
            <div class="part-main">
              <h3 class="part-symptom">«{html.escape(symptom)}»</h3>
              <p class="part-name">{html.escape(part)}</p>
            </div>
            <p class="part-fix">{html.escape(fix)}</p>
            <svg class="part-thumb" viewBox="{thumb_vb}" aria-hidden="true" focusable="false">{thumb_body}</svg>
          </li>''')
    return "\n".join(rows)


def exploded_css(meta):
    lines = ["/* Generated by tools/build.py. Assembly offsets for the opening animation. */"]
    for pid, (dx, dy) in meta["offsets"].items():
        lines.append(f'.part[data-part="{pid}"] {{ --dx: {dx}px; --dy: {dy}px; }}')
    return "\n".join(lines) + "\n"


def main():
    frag, meta = render()
    tpl = (ROOT / "index.template.html").read_text(encoding="utf-8")
    vb = " ".join(str(v) for v in meta["viewBox"])
    page = (tpl.replace("__VIEWBOX__", vb)
               .replace("__PARTS__", frag)
               .replace("__CALLOUTS__", callouts(meta))
               .replace("__SERVICES__", services())
               .replace("__FIG2__", f'<svg class="exploded-svg" viewBox="{vb}" aria-hidden="true" focusable="false">'
                                    f'{frag}{callouts(meta, linked=False)}</svg>'))
    (ROOT / "index.html").write_text(page, encoding="utf-8", newline="\n")
    (ROOT / "css" / "exploded.css").write_text(exploded_css(meta), encoding="utf-8", newline="\n")
    og = f'''<!doctype html>
<!-- Generated by tools/build.py. Source for assets/og-image.png (1200x630); see README. -->
<html lang="es-AR" data-theme="light" class="js">
<head><meta charset="utf-8">
<link rel="stylesheet" href="../css/styles.css"><link rel="stylesheet" href="../css/exploded.css">
<style>
body {{ width:1200px; height:630px; overflow:hidden; display:grid; grid-template-columns:1fr 520px; align-items:center; gap:40px; padding:0 64px; }}
.og-name {{ font-weight:700; font-stretch:112%; margin-top:36px; font-size:24px; }}
.display {{ font-size:84px; }}
.og-city {{ margin-top:28px; color:var(--ink-2); font-size:22px; }}
.og-name::before {{ content:""; display:inline-block; width:14px; height:14px; border-radius:50%; background:var(--signal); margin-right:12px; }}
</style></head>
<body><div><h1 class="display">Tu PC, desarmada y&nbsp;explicada.</h1>
<p class="og-name">Tu Nombre · Reparación de PC · Tu Ciudad</p></div>
<figure class="exploded is-open"><svg class="exploded-svg" viewBox="{vb}">{frag}{callouts(meta)}</svg></figure>
</body></html>'''
    (ROOT / "tools" / "og.html").write_text(og, encoding="utf-8", newline="\n")
    print("index.html, css/exploded.css and tools/og.html written")


if __name__ == "__main__":
    main()
